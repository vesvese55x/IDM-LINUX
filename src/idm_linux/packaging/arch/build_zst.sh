#!/usr/bin/env bash
# Arch Linux .pkg.tar.zst derleyici — makepkg/pacman GEREKTİRMEZ (CI/Ubuntu uyumlu).
# Çıktı: dist/idm-linux-<sürüm>-1-any.pkg.tar.zst
# Yeni depo düzeni: betik src/idm_linux/packaging/arch/ altındadır; kök dört üst dizin.
set -euo pipefail
cd "$(dirname "$0")/../../../.."
source src/idm_linux/packaging/vars.sh

PKGREL="1"
APP="src/idm_linux"
STAGE="build/zst/${APP_ID}"
rm -rf build/zst
mkdir -p "${STAGE}/opt/${APP_ID}/src/${APP##*/}" "${STAGE}/usr/bin" \
         "${STAGE}/usr/share/applications" "${STAGE}/usr/share/icons/hicolor/256x256/apps" \
         "${STAGE}/usr/share/licenses/${APP_ID}" dist

# 1) Uygulama ağacı: src/idm_linux içeriği → /opt/idm-linux/src/idm_linux
tar -cf - -C "${APP}" \
    --exclude=./__pycache__ --exclude=./p2p/__pycache__ --exclude='*.pyc' \
    --exclude=./tests --exclude=./docs --exclude=./packaging \
    . | tar -xf - -C "${STAGE}/opt/${APP_ID}/src/${APP##*/}"

# 2) Başlatıcı + kısayollar (deb/rpm ile birebir aynı düzen)
install -m 0755 "${APP}/packaging/launcher.sh" "${STAGE}/usr/bin/${APP_ID}"
ln -sf "${APP_ID}" "${STAGE}/usr/bin/IDM-LINUX"
ln -sf "${APP_ID}" "${STAGE}/usr/bin/IDM-Linux"
install -m 0644 "${APP}/packaging/idm-linux.desktop" "${STAGE}/usr/share/applications/${APP_ID}.desktop"
install -m 0644 LICENSE "${STAGE}/usr/share/licenses/${APP_ID}/LICENSE"

# 3) İkon
ICON=""
for c in "${APP}/assets/idm-linux-icon.png" "icons/idm-linux.png" "icons/icon.png" "icon.png" "idm-linux.png"; do
  if [ -f "$c" ]; then ICON="$c"; break; fi
done
if [ -z "$ICON" ]; then
  python3 -c "import PIL" 2>/dev/null || pip install --quiet pillow || true
  python3 "${APP}/packaging/icon_gen.py" "build/${APP_ID}.png"
  ICON="build/${APP_ID}.png"
fi
install -m 0644 "$ICON" "${STAGE}/usr/share/icons/hicolor/256x256/apps/${APP_ID}.png"

# 4) .PKGINFO (pacman için zorunlu tek dosya)
SIZE=$(du -sb "${STAGE}" | cut -f1)
cat > "${STAGE}/.PKGINFO" <<EOF
# Generated by idm-linux packaging
pkgname = ${APP_ID}
pkgbase = ${APP_ID}
pkgver = ${VERSION}-${PKGREL}
pkgdesc = IDM LINUX (BELGESELSEMO) — Internet Download Manager Linux entegrasyonu
url = ${HOMEPAGE}
packager = ${VENDOR}
arch = any
size = ${SIZE}
license = custom
depend = wine
depend = python
depend = tk
optdepend = yt-dlp: YouTube/video kaynak tespiti
optdepend = ffmpeg: birleştirme ve canlı kayıt
optdepend = aria2: hızlı çok parçalı indirme
optdepend = xdg-utils: masaüstü entegrasyonu
type = pkg
EOF

# 5) Zstandard arşivi
command -v zstd >/dev/null 2>&1 || { sudo apt-get update -qq && sudo apt-get install -y -qq zstd; }
tar --zstd -cf "dist/${APP_ID}-${VERSION}-${PKGREL}-any.pkg.tar.zst" -C "${STAGE}" .
echo "OK: dist/${APP_ID}-${VERSION}-${PKGREL}-any.pkg.tar.zst"
