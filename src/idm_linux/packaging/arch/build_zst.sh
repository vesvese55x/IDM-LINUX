#!/usr/bin/env bash
# Arch Linux .pkg.tar.zst derleyici — makepkg/pacman GEREKTİRMEZ (CI/Ubuntu uyumlu).
# Çıktı: dist/idm-linux-<sürüm>-1-any.pkg.tar.zst
# Yeni depo düzeni: betik src/idm_linux/packaging/arch/ altındadır; kök dört üst dizin.
#
# v3.14.2 DÜZELTMESİ — pamac "geçersiz veya bozuk paket" hatasının kök nedenleri:
#   1) .MTREE hiç yoktu     → makepkg HER pakette üretir; pamac doğrulaması buna güvenir
#   2) .PKGINFO'da builddate yoktu → libalpm descfile alanı (makepkg her zaman yazar)
#   3) tar girişleri "./" önekliydi → makepkg üretimi ÖNEKSİZTİR: .PKGINFO .MTREE usr/... opt/...
#   4) sahiplik kullanıcıya aitti → makepkg --owner=0 --group=0 (root) yazar
# Bu betik makepkg'nin ürettiği ALPM paketini BİREBİR taklit eder (metadata ilk
# girişler, gzip'li mtree manifest, root sahipliği, zstd sıkıştırma).
set -euo pipefail
cd "$(dirname "$0")/../../../.."
source src/idm_linux/packaging/vars.sh

PKGREL="1"
APP="src/idm_linux"
STAGE="build/zst/${APP_ID}"
OUT="dist/${APP_ID}-${VERSION}-${PKGREL}-any.pkg.tar.zst"
rm -rf build/zst
mkdir -p "${STAGE}/opt/${APP_ID}/src/${APP##*/}" "${STAGE}/usr/bin" \
         "${STAGE}/usr/share/applications" "${STAGE}/usr/share/icons/hicolor/256x256/apps" \
         "${STAGE}/usr/share/licenses/${APP_ID}" dist

# 1) Uygulama ağacı: src/idm_linux içeriği → /opt/idm-linux/src/idm_linux
tar -cf - -C "${APP}" \
    --exclude=./__pycache__ --exclude=./p2p/__pycache__ --exclude='*.pyc' \
    --exclude=./tests --exclude=./docs --exclude=./packaging \
    . | tar -xf - -C "${STAGE}/opt/${APP_ID}/src/${APP##*/}"

# 2) Başlatıcı + kısayollar (deb/rpm ile birebir aynı düzen)
install -m 0755 "${APP}/packaging/launcher.sh" "${STAGE}/usr/bin/${APP_ID}"
ln -sf "${APP_ID}" "${STAGE}/usr/bin/IDM-LINUX"
ln -sf "${APP_ID}" "${STAGE}/usr/bin/IDM-Linux"
install -m 0644 "${APP}/packaging/idm-linux.desktop" "${STAGE}/usr/share/applications/${APP_ID}.desktop"
install -m 0644 LICENSE "${STAGE}/usr/share/licenses/${APP_ID}/LICENSE"

# 3) İkon
ICON=""
for c in "${APP}/assets/idm-linux-icon.png" "icons/idm-linux.png" "icons/icon.png" "icon.png" "idm-linux.png"; do
  if [ -f "$c" ]; then ICON="$c"; break; fi
done
if [ -z "$ICON" ]; then
  python3 -c "import PIL" 2>/dev/null || pip install --quiet pillow || true
  python3 "${APP}/packaging/icon_gen.py" "build/${APP_ID}.png"
  ICON="build/${APP_ID}.png"
fi
install -m 0644 "$ICON" "${STAGE}/usr/share/icons/hicolor/256x256/apps/${APP_ID}.png"

# 4) .PKGINFO — builddate DAHİL (libalpm zorunlu alan)
SIZE=$(du -sb "${STAGE}" | cut -f1)
BUILDDATE=$(date +%s)
cat > "${STAGE}/.PKGINFO" <<EOF
# Generated by idm-linux packaging
pkgname = ${APP_ID}
pkgbase = ${APP_ID}
pkgver = ${VERSION}-${PKGREL}
pkgdesc = IDM LINUX (BELGESELSEMO) — Internet Download Manager Linux entegrasyonu
url = ${HOMEPAGE}
builddate = ${BUILDDATE}
packager = ${VENDOR}
arch = any
size = ${SIZE}
license = custom
depend = wine
depend = python
depend = tk
optdepend = yt-dlp: YouTube/video kaynak tespiti
optdepend = ffmpeg: birleştirme ve canlı kayıt
optdepend = aria2: hızlı çok parçalı indirme
optdepend = xdg-utils: masaüstü entegrasyonu
type = pkg
EOF

# 5) .MTREE — gzip'li mtree manifest (makepkg her pakette üretir; pamac güvenir)
python3 "${APP}/packaging/arch/mtree_gen.py" "${STAGE}"

# 6) zstd arşivi — makepkg düzeni: metadata İLK iki giriş, yollar ÖNEKSİZ,
#    sahiplik root (0). zstd CLI yoksa Python zstandard ile stream sıkıştırma.
TOPS=()
for d in "${STAGE}"/*; do TOPS+=("$(basename "$d")"); done
if command -v zstd >/dev/null 2>&1; then
  tar --zstd -cf "${OUT}" --owner=0 --group=0 --numeric-owner -C "${STAGE}" .PKGINFO .MTREE "${TOPS[@]}"
else
  TMP_TAR="${OUT%.zst}.tmp.tar"
  tar -cf "${TMP_TAR}" --owner=0 --group=0 --numeric-owner -C "${STAGE}" .PKGINFO .MTREE "${TOPS[@]}"
  python3 - "$TMP_TAR" "${OUT}" <<'PYEOF'
import sys
try:
    import zstandard as zstd
except ImportError:
    sys.exit("HATA: zstd CLI da python zstandard da yok — paket sıkıştırılamaz")
src, dst = sys.argv[1], sys.argv[2]
cctx = zstd.ZstdCompressor(level=9)
with open(src, "rb") as fi, open(dst, "wb") as fo:
    cctx.copy_stream(fi, fo)
PYEOF
  rm -f "${TMP_TAR}"
fi
echo "OK: ${OUT}"
